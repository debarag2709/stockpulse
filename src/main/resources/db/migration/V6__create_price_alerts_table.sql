
CREATE TABLE price_alerts (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              user_id BIGINT NOT NULL,
                              stock_id BIGINT NOT NULL,

                              target_price NUMERIC(15, 4) NOT NULL,
                              condition VARCHAR(10) NOT NULL,
                              status VARCHAR(15) NOT NULL DEFAULT 'ACTIVE',

                              created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              triggered_at TIMESTAMP WITH TIME ZONE,

                              CONSTRAINT fk_price_alerts_user
                                  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,

                              CONSTRAINT fk_price_alerts_stock
                                  FOREIGN KEY (stock_id) REFERENCES stocks(id) ON DELETE CASCADE,

                              CONSTRAINT chk_price_alerts_target_price
                                  CHECK (target_price > 0),

                              CONSTRAINT chk_price_alerts_condition
                                  CHECK (condition IN ('ABOVE', 'BELOW')),

                              CONSTRAINT chk_price_alerts_status
                                  CHECK (status IN ('ACTIVE', 'TRIGGERED', 'CANCELLED'))
);

CREATE INDEX idx_price_alerts_user_status
    ON price_alerts(user_id, status);

CREATE INDEX idx_price_alerts_stock_status
    ON price_alerts(stock_id, status);
